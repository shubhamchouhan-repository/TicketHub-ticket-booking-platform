CREATE TABLE bookings (
    id              UUID PRIMARY KEY,
    customer_id     VARCHAR(100)   NOT NULL,
    customer_email  VARCHAR(200),
    show_id         BIGINT         NOT NULL,
    event_title     VARCHAR(200)   NOT NULL,
    venue_name      VARCHAR(200)   NOT NULL,
    show_start_time TIMESTAMPTZ    NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    currency        VARCHAR(3)     NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    idempotency_key VARCHAR(100),
    failure_reason  VARCHAR(300),
    created_at      TIMESTAMPTZ    NOT NULL,
    updated_at      TIMESTAMPTZ    NOT NULL,
    expires_at      TIMESTAMPTZ    NOT NULL,
    confirmed_at    TIMESTAMPTZ,
    version         BIGINT         NOT NULL DEFAULT 0,
    -- ST-53: a retried request with the same key can never create a second booking
    CONSTRAINT uq_booking_idempotency UNIQUE (customer_id, idempotency_key)
);
CREATE INDEX idx_bookings_customer ON bookings (customer_id);
CREATE INDEX idx_bookings_due ON bookings (status, expires_at);
CREATE INDEX idx_bookings_show ON bookings (show_id, status);

CREATE TABLE booking_seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  UUID        NOT NULL REFERENCES bookings (id),
    show_id     BIGINT      NOT NULL,
    seat_id     BIGINT      NOT NULL,
    row_label   VARCHAR(5)  NOT NULL,
    seat_number INT         NOT NULL,
    category    VARCHAR(20) NOT NULL,
    state       VARCHAR(20) NOT NULL,
    reserved_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_booking_seats_booking ON booking_seats (booking_id);
CREATE INDEX idx_booking_seats_show ON booking_seats (show_id);

-- ST-08: concurrency protection enforced by the DATABASE.
-- A seat of a show can be RESERVED or BOOKED by at most one booking at a time.
-- Released seats (state AVAILABLE) are kept as history and excluded from the index.
CREATE UNIQUE INDEX uq_active_show_seat ON booking_seats (show_id, seat_id) WHERE state <> 'AVAILABLE';
