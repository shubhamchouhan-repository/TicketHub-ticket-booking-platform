-- ============================================================================
-- Phase 2 (Booking)
--   S3  outbox_events : events are written HERE inside the business transaction; a relay job
--                       publishes them to Kafka later. No more "committed but never published".
--   S4  inbox_events  : ids of events already handled (idempotent consumer for Payment events).
--   S7  saga_log      : one row per saga step, so we can answer "where is booking X and why?".
--   S6  bookings.aggregate_version         : counter stamped on every event Booking publishes.
--       bookings.last_payment_event_version: newest Payment event version already applied
--                                            (older/duplicate ones are ignored).
--       bookings.saga_state                : where the booking is in the payment/refund saga.
-- ============================================================================
CREATE TABLE outbox_events (
    id           UUID         PRIMARY KEY,                       -- = eventId (deterministic => append is idempotent)
    seq          BIGINT GENERATED ALWAYS AS IDENTITY,            -- publish order
    aggregate_id UUID         NOT NULL,                          -- the booking id
    event_type   VARCHAR(60)  NOT NULL,
    topic        VARCHAR(100) NOT NULL,
    kafka_key    VARCHAR(100) NOT NULL,                          -- booking id => same partition => ordered (S6)
    payload      TEXT         NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL,
    published_at TIMESTAMPTZ,
    attempts     INT          NOT NULL DEFAULT 0
);
CREATE INDEX idx_outbox_unpublished ON outbox_events (seq) WHERE published_at IS NULL;

CREATE TABLE inbox_events (
    event_id    UUID        PRIMARY KEY,
    event_type  VARCHAR(60) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE saga_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id UUID         NOT NULL,
    saga_state VARCHAR(20)  NOT NULL,
    step       VARCHAR(60)  NOT NULL,
    detail     VARCHAR(300),
    created_at TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_saga_log_booking ON saga_log (booking_id, id);

ALTER TABLE bookings ADD COLUMN aggregate_version          BIGINT      NOT NULL DEFAULT 0;
ALTER TABLE bookings ADD COLUMN last_payment_event_version BIGINT      NOT NULL DEFAULT 0;
ALTER TABLE bookings ADD COLUMN saga_state                 VARCHAR(20) NOT NULL DEFAULT 'PAYMENT_PENDING';
-- bookings that were already CONFIRMED before this migration
UPDATE bookings SET saga_state = 'CONFIRMED' WHERE status = 'CONFIRMED';
UPDATE bookings SET saga_state = 'FAILED'    WHERE status IN ('EXPIRED', 'PAYMENT_FAILED', 'CANCELLED');
