CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200)  NOT NULL,
    description VARCHAR(2000),
    type        VARCHAR(20)   NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    poster_url  VARCHAR(500),
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX idx_events_status ON events (status);

CREATE TABLE venues (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200) NOT NULL,
    city       VARCHAR(100) NOT NULL,
    address    VARCHAR(300),
    status     VARCHAR(20)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    version    BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE venue_seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id    BIGINT      NOT NULL REFERENCES venues (id),
    row_label   VARCHAR(5)  NOT NULL,
    seat_number INT         NOT NULL,
    category    VARCHAR(20) NOT NULL,
    CONSTRAINT uq_venue_seat UNIQUE (venue_id, row_label, seat_number)
);

CREATE TABLE shows (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT         NOT NULL REFERENCES events (id),
    venue_id     BIGINT         NOT NULL REFERENCES venues (id),
    start_time   TIMESTAMPTZ    NOT NULL,
    end_time     TIMESTAMPTZ    NOT NULL,
    ticket_price NUMERIC(12, 2) NOT NULL,
    currency     VARCHAR(3)     NOT NULL,
    status       VARCHAR(20)    NOT NULL,
    created_at   TIMESTAMPTZ    NOT NULL,
    updated_at   TIMESTAMPTZ    NOT NULL,
    version      BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT chk_show_times CHECK (end_time > start_time),
    CONSTRAINT chk_show_price CHECK (ticket_price > 0)
);
CREATE INDEX idx_shows_event ON shows (event_id);
CREATE INDEX idx_shows_status ON shows (status);
